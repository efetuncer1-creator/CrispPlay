#
# The C++ port of CouchSubs needs the .NET char predicates (IsLetter, IsUpper,
# IsPunctuation, ...) and simple case mapping without depending on ICU, Qt or
# Win32. This script writes compact range tables from Python's unicodedata.
#
#   python -I tools/gen_unicode_tables.py > src/UnicodeTables.inc
import sys
import unicodedata

CATS = ["Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe",
        "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co", "Cn"]
INDEX = {c: i for i, c in enumerate(CATS)}


def category_runs():
    runs = []
    last = None
    for cp in range(0x110000):
        cat = unicodedata.category(chr(cp))
        if cat != last:
            runs.append((cp, INDEX[cat]))
            last = cat
    return runs


def case_runs(func):
    """(start, end, stride, delta) runs of a simple one-to-one case mapping."""
    pairs = []
    for cp in range(0x110000):
        ch = chr(cp)
        if 0xD800 <= cp <= 0xDFFF:
            continue
        mapped = func(ch)
        if len(mapped) == 1 and mapped != ch:
            pairs.append((cp, ord(mapped) - cp))
    runs = []
    for cp, delta in pairs:
        if runs:
            start, end, stride, d = runs[-1]
            if d == delta:
                step = cp - end
                if (start == end and step in (1, 2)) or step == stride:
                    runs[-1] = (start, cp, step if start == end else stride, d)
                    continue
        runs.append((cp, cp, 1, delta))
    return runs


def emit(out):
    out.write("// Generated by custom/subs/core/tools/gen_unicode_tables.py from Unicode %s. Do not edit.\n"
              % unicodedata.unidata_version)
    cats = category_runs()
    out.write("static constexpr CategoryRun kCategoryRuns[] = {\n")
    for i in range(0, len(cats), 8):
        out.write("  " + " ".join("{0x%X,%d}," % r for r in cats[i:i + 8]) + "\n")
    out.write("};\n")
    for name, func in (("kLowerRuns", str.lower), ("kUpperRuns", str.upper)):
        runs = case_runs(func)
        out.write("static constexpr CaseRun %s[] = {\n" % name)
        for i in range(0, len(runs), 6):
            out.write("  " + " ".join("{0x%X,0x%X,%d,%d}," % r for r in runs[i:i + 6]) + "\n")
        out.write("};\n")


if __name__ == "__main__":
    sys.stdout.reconfigure(newline="\n")
    emit(sys.stdout)
